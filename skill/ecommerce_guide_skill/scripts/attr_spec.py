"""闭词表的视觉属性定义。

为什么换掉原来的 `parts`
    原来的目标是"列出 3-5 个看得见的结构特征"，它在数学上是**欠定**的：
    同一张图合法答案很多。实测两个老师（4B / 30B）用**同一句指令**标注，
    部件集合只有 13.3% 完全一致（归一化后 Jaccard 0.414）。
    这意味着模型即使完全看懂图，也不可能命中那个任意选择 —— 目标本身错了。

改成什么
    每个属性都是**互斥、有唯一确定答案**的判断题，且选项是闭词表：
        鞋帮高度 ∈ {低帮, 中帮, 高帮}
        开合方式 ∈ {拉链, 魔术贴, 一脚蹬, 拉链式}
    这类属性的正确答案由图本身决定，不同标注者应当谈得拢；
    谈不拢说明该属性依然不可靠，就该剔除。所以先测一致性，再决定用不用。

统一给一个"不确定"选项，方便统计模型有多少次弃权。
"""

