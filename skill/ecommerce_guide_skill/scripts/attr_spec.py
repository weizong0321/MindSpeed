def prompt_for(cat):
    spec = ATTRS.get(cat)
    if not spec:
        return None, None
    keys = [k for k, _, _ in spec]
    lines = []
    for k, desc, opts in spec:
        lines.append(f'- "{k}"：{desc}。只能从这些里选一个：{" / ".join(opts)}'
                     f' / {UNSURE}')
    body = "\n".join(lines)
    example = "{" + ", ".join(f'"{k}": "..."' for k in keys) + "}"
    q = (f"只看这张图里商品本身的样子，判断下面几项。\n{body}\n\n"
         f"看不清或图上没有就写「{UNSURE}」。禁止解释，禁止输出多余字段。\n"
         f"只输出一行 JSON：\n{example}")
    return q, keys
