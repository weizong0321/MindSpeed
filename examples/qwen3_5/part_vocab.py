# 明确禁止出现的"不是商品本体"的词。
# 注意：这里绝对不能用单字（"手"/"脚"/"裤"/"人"）—— 它们会把
# 提手、手柄、一脚蹬、裤脚、裤腿 这些**合法**词一起挡掉。
# 单字过滤交给按品类的白名单去做（鞋子白名单里没有"裤脚"，自然就挡住了）。
